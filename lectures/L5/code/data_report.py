"""Build an offline single-file HTML report for the course's leaf measurements.

Python standard library only; no model, network requests or invented results.
Usage: python data_report.py leaves.csv --output report.html
Existing output is never overwritten. Use a new path for a new build.
"""
import argparse
import csv
import html
import json
from collections import Counter
from pathlib import Path


def build(csv_path: Path) -> str:
    raw = csv_path.read_text(encoding='utf-8-sig')
    rows = list(csv.DictReader(raw.splitlines()))
    required = ['Leaf height', 'Leaf width', 'Tree type']
    if not rows or list(rows[0]) != required:
        raise ValueError(f'Expected nonempty CSV with columns {required}')
    if any(None in row or any(v is None for v in row.values()) for row in rows):
        raise ValueError('CSV rows have inconsistent numbers of fields')
    counts = Counter(r['Tree type'] or '(missing)' for r in rows)
    missing = sum(v.strip() == '' for r in rows for v in r.values())
    duplicates = len(rows)-len({tuple(r.values()) for r in rows})
    assert sum(counts.values()) == len(rows)
    # JSON inside a script must not contain literal HTML closing tags.
    encoded = json.dumps({'rows': rows, 'columns': required}).replace('<', '\\u003c')
    bars=[]
    for i,(name,count) in enumerate(sorted(counts.items())):
        y=14+i*55
        width=500*count/max(counts.values())
        bars.append(f'<text x="5" y="{y+24}">{html.escape(name)}</text>'
                    f'<rect x="140" y="{y}" width="{width:.2f}" height="35" rx="4" />'
                    f'<text x="{150+width:.2f}" y="{y+24}">{count}</text>')
    options=''.join(f'<option value="{html.escape(k, quote=True)}">{html.escape(k)}</option>'
                    for k in sorted({r['Tree type'] for r in rows}))
    page = '''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Leaf data — an interactive report</title>
<style>
:root{font-family:system-ui,sans-serif;color:#17212b;background:#f2f6f8}
body{max-width:1000px;margin:auto;padding:32px}h1{color:#12355b;font-size:2.5rem;margin-bottom:8px}
p{line-height:1.5}.cards{display:flex;gap:16px;flex-wrap:wrap}.card{flex:1;min-width:130px;background:white;padding:20px;border-top:4px solid #007f86;border-radius:8px}.card strong{font-size:2rem;display:block;color:#007f86}
section{background:white;padding:24px;margin:24px 0;border-radius:8px}svg{width:100%;max-height:240px}svg rect{fill:#007f86}svg text{font:18px system-ui;fill:#12355b}
.controls{display:flex;flex-wrap:wrap;gap:20px;align-items:end}input,select{font:inherit;padding:8px;display:block;max-width:100%;box-sizing:border-box}table{width:100%;border-collapse:collapse}th,td{text-align:left;border-bottom:1px solid #d7e5ea;padding:9px}.scroll{max-height:350px;overflow:auto}th{position:sticky;top:0;background:#eef7f8}code{overflow-wrap:anywhere}.note{color:#52616b}
@media(max-width:600px){body{padding:12px}h1{font-size:1.8rem}section{padding:16px}}
</style></head><body>
<h1>Leaf measurements</h1><p>Inspect the dataset before you train a classifier.</p>
<div class="cards"><div class="card"><strong>__ROWS__</strong>rows retained</div><div class="card"><strong>__CLASSES__</strong>class labels</div><div class="card"><strong>__MISSING__</strong>empty cells</div><div class="card"><strong>__DUPLICATES__</strong>repeated full rows</div></div>
<section><h2>Class balance</h2><svg viewBox="0 0 740 __BARHEIGHT__" role="img" aria-label="Class counts: __COUNTLABEL__">__BARS__</svg></section>
<section><h2>Explore the measurements</h2><div class="controls"><label>Class<select id="class"><option value="__ALL_ROWS__">All classes</option>__OPTIONS__</select></label><label>Search any cell<input id="query" type="search" placeholder="e.g. 12.3"></label></div>
<p id="shown" aria-live="polite"></p><div class="scroll"><table><thead><tr><th>Leaf height</th><th>Leaf width</th><th>Tree type</th></tr></thead><tbody id="rows"></tbody></table></div></section>
<section><h2>What this does and does not establish</h2><p>Source: <code>__SOURCE__</code>. All CSV rows are retained. Repeated rows are counted beyond the first exact occurrence; empty cells contain no non-whitespace characters.</p><p class="note">This is a descriptive report, not a trained classifier. Repeated measurements deserve investigation before splitting. Measurement units and specimen identities are not established by the column names alone.</p><p class="note">Generated by data_report.py with Python's standard library. This file makes no external network requests.</p></section>
<script id="data" type="application/json">__DATA__</script>
<script>
const data=JSON.parse(document.getElementById('data').textContent);
const klass=document.getElementById('class'),query=document.getElementById('query'),body=document.getElementById('rows');
function render(){
 const q=query.value.toLowerCase();
 const filtered=data.rows.filter(r=>(klass.selectedIndex===0||r['Tree type']===klass.value)&&data.columns.some(c=>r[c].toLowerCase().includes(q)));
 body.replaceChildren();
 for(const row of filtered){const tr=document.createElement('tr');for(const c of data.columns){const td=document.createElement('td');td.textContent=row[c];tr.append(td);}body.append(tr);}
 document.getElementById('shown').textContent=`${filtered.length} of ${data.rows.length} rows shown`;
}
klass.addEventListener('change',render);query.addEventListener('input',render);render();
</script></body></html>'''
    replacements={'__ROWS__':str(len(rows)), '__CLASSES__':str(len(counts)),
        '__MISSING__':str(missing), '__DUPLICATES__':str(duplicates),
        '__BARHEIGHT__':str(len(counts)*55+15), '__BARS__':''.join(bars),
        '__COUNTLABEL__':html.escape(', '.join(f'{k} {v}' for k,v in sorted(counts.items())),quote=True),
        '__OPTIONS__':options, '__SOURCE__':html.escape(csv_path.name), '__DATA__':encoded}
    # Substitute once so file content cannot become a second template instruction.
    import re
    return re.sub('|'.join(map(re.escape,replacements)),lambda m: replacements[m.group()],page)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('csv',type=Path)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    report=build(args.csv)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    with args.output.open('x',encoding='utf-8') as f:
        f.write(report)
    print(f'Created {args.output}; open it in a browser.')

if __name__=='__main__':
    main()
